import { describe, expect, it } from 'vitest';
import { generatePageRouteTsx, summarizePage } from '@/lib/render/page-preview';
import { createBlankPage } from '@/lib/schema/page';
import { createBlockInstance } from '@/lib/catalog/blocks';

describe('page preview helpers', () => {
  it('summarizes blocks', () => {
    const page = createBlankPage({ id: 'home', route: '/', title: 'Home' });
    page.blocks = [createBlockInstance('hero', 'h1')];
    page.agent.tldr = 'TLDR';
    const summary = summarizePage(page);
    expect(summary.blockCount).toBe(1);
    expect(summary.tldr).toBe('TLDR');
    expect(summary.outline[0]).toMatch(/^Hero:/);
  });

  it('generates a route stub referencing the page id', () => {
    const page = createBlankPage({ id: 'services', route: '/services', title: 'Services' });
    const tsx = generatePageRouteTsx(page);
    expect(tsx).toContain('services.page.yaml');
    expect(tsx).toContain('Generated by FWP');
  });
});
