import type { BlockInstance } from '@/lib/catalog/blocks';
import type { PageDocument } from '@/lib/schema/page';

/** Plain-text / structural preview of a page document for Edit/Preview modes. */
export function summarizePage(page: PageDocument): {
  title: string;
  tldr: string;
  blockCount: number;
  outline: string[];
} {
  return {
    title: page.metadata.title,
    tldr: page.agent.tldr || page.metadata.description,
    blockCount: page.blocks.length,
    outline: page.blocks.map((block) => outlineBlock(block))
  };
}

function outlineBlock(block: BlockInstance): string {
  switch (block.type) {
    case 'hero':
      return `Hero: ${block.props.headline}`;
    case 'prose':
      return `Prose: ${block.props.heading || block.props.body.slice(0, 40)}`;
    case 'image':
      return `Image: ${block.props.src}`;
    case 'serviceCards':
      return `Services: ${block.props.items.length} cards`;
    case 'ctaBand':
      return `CTA: ${block.props.heading}`;
    case 'faq':
      return `FAQ: ${block.props.items.length} items`;
    case 'people':
      return `People: ${block.props.people.length}`;
    case 'partnerLogos':
      return `Partners: ${block.props.partners.length}`;
    case 'articleList':
      return `Articles (${block.props.source})`;
    case 'contactForm':
      return `Contact: ${block.props.heading}`;
    default:
      return 'Block';
  }
}

/**
 * Emit a minimal TSX route stub for document-driven sites.
 * Authors never edit this by hand; FWP regenerates it from the page document.
 */
export function generatePageRouteTsx(page: PageDocument): string {
  return `/* Generated by FWP — do not edit by hand */
import { renderPageDocument } from '@/lib/fwp/render-page';
import doc from '@/content/pages/${page.id}.page.yaml';

export const metadata = {
  title: ${JSON.stringify(page.metadata.title)},
  description: ${JSON.stringify(page.metadata.description)},
  robots: ${page.metadata.robots === 'noindex' ? '{ index: false, follow: false }' : '{ index: true, follow: true }'}
};

export default function Page() {
  return renderPageDocument(doc);
}
`;
}
